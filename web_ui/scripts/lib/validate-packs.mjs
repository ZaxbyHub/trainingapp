/**
 * validate-packs.mjs — the dist/packs/ verification seam (issue #266, AC16).
 *
 * Wired into scripts/validate-build.mjs (both validation paths — the default
 * `validate-build` and `validate-build --airgap` — execute that script, so the
 * pack gate covers both). For every entry in packs.manifest.json the built
 * dist/packs/ must contain the named file with the recorded size and SHA-256,
 * and no staged pack file may be a Git-LFS pointer stub (lfs-detect.mjs).
 * Every failure names the pack.
 *
 * What the SHA-256 check is NOT (recorded maintainer decision, comment
 * 6825526111): it is corruption/coverage verification of the staged artifact
 * against the manifest written by the same build — explicitly NOT a
 * hostile-host defense. A hostile host that serves different bytes controls
 * the manifest too; transport-hostile threats are handled elsewhere (HTTPS
 * hosting requirements, ADR-0012).
 *
 * Side-effect-free module: every path is injected; validate-build.mjs calls
 * `verifyDistPacks` with the real ones.
 */
import { createHash } from 'node:crypto';
import { createReadStream, existsSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';

import { isLfsPointer } from './lfs-detect.mjs';

/**
 * Stream a file through SHA-256 (pack zips can be large; never readFileSync).
 * @param {string} filePath
 * @returns {Promise<string>} hex digest
 */
export async function sha256OfFile(filePath) {
  const hash = createHash('sha256');
  for await (const chunk of createReadStream(filePath)) {
    hash.update(chunk);
  }
  return hash.digest('hex');
}

/**
 * Verify dist/packs/ against packs.manifest.json.
 *
 * @param {object} opts
 * @param {string} opts.distPacksDir The built packs directory (dist/packs).
 * @param {string} opts.manifestPath The staged manifest path (dist/packs/packs.manifest.json).
 * @param {(message: string) => void} opts.onProblem Failure collector (each names the pack).
 * @param {(filePath: string) => Promise<string>} [opts.sha256Impl] Hash seam (tests).
 */
export async function verifyDistPacks(opts) {
  const {
    distPacksDir,
    manifestPath,
    onProblem,
    sha256Impl = sha256OfFile,
  } = opts;

  if (!existsSync(manifestPath)) {
    onProblem(
      `dist packs manifest is missing: ${manifestPath} not found — run \`npm run prepare-packs\` before building.`,
    );
    return;
  }
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  } catch (err) {
    onProblem(`packs.manifest.json is not valid JSON: ${err instanceof Error ? err.message : err}`);
    return;
  }
  if (manifest === null || typeof manifest !== 'object' || !Array.isArray(manifest.packs)) {
    onProblem('packs.manifest.json has no packs[] array');
    return;
  }

  if (!existsSync(distPacksDir)) {
    if (manifest.packs.length > 0) {
      onProblem(
        `dist/packs/ is missing while packs.manifest.json lists ${manifest.packs.length} pack(s) — run \`npm run prepare-packs\` before building.`,
      );
    }
    return;
  }

  for (const entry of manifest.packs) {
    const label = `pack "${entry.id}" (${entry.file})`;
    if (typeof entry.file !== 'string' || entry.file.length === 0) {
      onProblem(`${label}: manifest entry has no file name`);
      continue;
    }
    // The manifest is generated by prepare-packs; a file name that escapes
    // the packs dir can only be hand-edited — refuse it rather than read it.
    const normalized = path.normalize(entry.file).split(path.sep).join('/');
    if (normalized.startsWith('..') || path.isAbsolute(normalized)) {
      onProblem(`${label}: manifest file name escapes the packs directory (refused): ${entry.file}`);
      continue;
    }
    const file = path.join(distPacksDir, normalized);
    if (!existsSync(file)) {
      onProblem(`required pack archive missing from dist: packs/${entry.file} (pack "${entry.id}") — run \`npm run prepare-packs\` before building.`);
      continue;
    }
    const size = statSync(file).size;
    if (typeof entry.size === 'number' && size !== entry.size) {
      onProblem(
        `pack "${entry.id}": size mismatch for packs/${entry.file}: manifest says ${entry.size} bytes, dist file is ${size} bytes. File is corrupt or was replaced.`,
      );
      continue;
    }
    if (isLfsPointer(file)) {
      onProblem(
        `dist pack archive is a Git-LFS pointer stub, not the real archive: packs/${entry.file} (pack "${entry.id}"). Run \`git lfs pull\` and rebuild.`,
      );
      continue;
    }
    if (typeof entry.sha256 === 'string' && entry.sha256.length === 64) {
      const actual = await sha256Impl(file);
      if (actual.toLowerCase() !== entry.sha256.toLowerCase()) {
        onProblem(
          `pack "${entry.id}": sha256 mismatch for packs/${entry.file}: expected ${entry.sha256}, got ${actual}. File is corrupt or was replaced.`,
        );
      }
    }
  }
}
