// i320-pdf-parity.test.ts — FROZEN ACCEPTANCE SPEC (issue #320 AC2 / check
// C2, trace 320-269-parse-isolation-chat-integrity), authored by the
// issue-tracer ARM'S-LENGTH CHECK AUTHOR at base 5d1f7338, before any fix.
//
// AC2: the desktop .pdf parse (pdfjs-dist) moves into the doc-worker child
// process, and its extraction output stays BYTE-IDENTICAL across the move —
// ADR-0004 chunk ids derive from the extracted text, and the per-page text
// feeds the chunker's page attribution, so the bar is the same as #319's.
//
// THE GOLDEN (contracts/fixtures/pdf-parity/):
//   parity.pdf            — a deterministic two-page Helvetica PDF generated by
//                           .agents/issue-traces/320-269-parse-isolation-chat-integrity/repro/gen-pdf-fixture.mjs
//                           (its header comment carries a NUL byte, so git
//                           treats it as binary and never EOL-converts it).
//   parity.expected.json  — JSON.stringify of the FULL ExtractionResultNode
//                           ({ text, pages }) that the PRE-MIGRATION in-main
//                           extractDocumentFromFile produced at base 5d1f7338
//                           (repro/capture-pdf-golden.mjs). One line, newlines
//                           escaped, no trailing newline — autocrlf-immune.
// Both files' sha256 are pinned below so silent fixture drift fails loudly.
//
// RED AT BASE (5d1f7338): this file statically imports
// desktop/main/backend/ingest/doc-worker.js, which does not exist until the
// fix lands — the whole file fails to load with an import-resolution error.
//
// FROZEN CONTRACT (subset of i320-doc-parsers-out-of-main.test.ts's):
//   extractDocOutOfProcess(filePath, opts?) runs the doc-worker child (node
//   fork outside Electron, default childPath = docWorkerChildPath()) and
//   resolves { text, pages? }; for .pdf the child reports the per-page text,
//   and the public extractDocumentFromFile result equals the pre-migration
//   result exactly.
import { afterEach, describe, expect, it } from 'vitest';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractDocumentFromFile } from '../../main/backend/ingest/extractors.js';
import { extractDocOutOfProcess, setDocWorkerForkFn } from '../../main/backend/ingest/doc-worker.js';

const THIS_DIR = path.dirname(fileURLToPath(import.meta.url));
const PARITY_DIR = path.resolve(THIS_DIR, '../../../contracts/fixtures/pdf-parity');
const PARITY_PDF = path.join(PARITY_DIR, 'parity.pdf');
const PARITY_GOLDEN = path.join(PARITY_DIR, 'parity.expected.json');
// Pinned at capture time (base 5d1f7338); see the trace's repro/ scripts.
const PARITY_PDF_SHA256 = '1e372be8fd24bbbab1eb3601e32514688e4ef7f9adc9eb8008ead25ad1d475be';
const PARITY_GOLDEN_SHA256 = 'ef359aa4e4cffb67c5ba188fdef5c84a58d260a65a5ed120250b6a2b53e85dce';

interface Golden {
  text: string;
  pages: Array<{ pageNumber: number; text: string }>;
}

const tempDirs: string[] = [];

afterEach(() => {
  setDocWorkerForkFn(null);
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop();
    if (dir !== undefined) fs.rmSync(dir, { recursive: true, force: true });
  }
});

function sha256(file: string): string {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function readGolden(): Golden {
  return JSON.parse(fs.readFileSync(PARITY_GOLDEN, 'utf8')) as Golden;
}

/** Bound a promise so a broken runner fails the test instead of hanging it. */
function within<T>(promise: Promise<T>, ms: number): Promise<T> {
  return Promise.race([
    promise,
    new Promise<T>((_resolve, reject) => {
      setTimeout(() => reject(new Error(`spec guard: no settle within ${ms}ms`)), ms);
    }),
  ]);
}

describe('#320 AC2: .pdf extraction is byte-identical after moving into the doc-worker child', () => {
  it('P0: the committed fixture and golden are the captured bytes (no drift) and carry real multi-page text', () => {
    expect(sha256(PARITY_PDF), 'parity.pdf drifted from the captured fixture').toBe(PARITY_PDF_SHA256);
    expect(sha256(PARITY_GOLDEN), 'parity.expected.json drifted from the base capture').toBe(PARITY_GOLDEN_SHA256);
    const golden = readGolden();
    // Anti-vacuity: the golden is real extracted text over two pages.
    expect(golden.text.length).toBeGreaterThan(100);
    expect(golden.text).toContain('Issue 320 PDF parity fixture');
    expect(golden.pages).toHaveLength(2);
    expect(golden.pages.map((p) => p.pageNumber)).toEqual([1, 2]);
    expect(golden.pages.map((p) => p.text).join('\n\n')).toBe(golden.text);
  });

  it('P1: extractDocOutOfProcess (real node-fork child, default childPath) equals the golden byte for byte', async () => {
    setDocWorkerForkFn(null); // outside Electron: the node fork default
    const golden = readGolden();
    const result = await within(extractDocOutOfProcess(PARITY_PDF, { timeoutMs: 60_000 }), 90_000);
    expect(result.text).toBe(golden.text);
    expect(result.pages).toEqual(golden.pages);
  }, 120_000);

  it('P2: the public extractDocumentFromFile equals the golden byte for byte (path with a space)', async () => {
    setDocWorkerForkFn(null);
    const golden = readGolden();
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pdf parity '));
    tempDirs.push(dir);
    const copy = path.join(dir, 'parity copy.pdf');
    fs.copyFileSync(PARITY_PDF, copy);

    const result = await within(extractDocumentFromFile(copy), 90_000);
    expect(result.text).toBe(golden.text);
    expect(result.pages).toEqual(golden.pages);
    // The whole result, not just its fields: nothing added, nothing lost.
    expect(JSON.parse(JSON.stringify(result))).toEqual(golden);

    // A zip cap is meaningless for .pdf: it must not change the output.
    const capped = await within(extractDocumentFromFile(copy, { maxZipBytes: 100 }), 90_000);
    expect(JSON.parse(JSON.stringify(capped))).toEqual(golden);
  }, 120_000);
});
